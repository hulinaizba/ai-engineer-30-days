import pandas as pd

url = "https://raw.githubusercontent.com/datasciencedojo/datasets/master/titanic.csv"
df = pd.read_csv(url)

print("=== Первичный разбор ===")
print("Размер (строки, колонки):", df.shape)
print("\nКолонки:", df.columns.tolist())
print("\nПервые 5 строк:")
print(df.head())
print("\nИнформация:")
print(df.info())

print("\n=== Ответы на вопросы ===")

# 1. Сколько всего пассажиров?
print("Всего пассажиров:", len(df))

# 2. Сколько выжило / погибло
print("\nВыжили / Погибли:")
print(df["Survived"].value_counts())

# 3. Процент выживших
survival_rate = df["Survived"].mean() * 100
print(f"\nПроцент выживших: {survival_rate:.1f}%")

# 4. Средний возраст
print("Средний возраст:", round(df["Age"].mean(), 1))

# 5. Средняя цена билета
print("Средняя цена билета:", round(df["Fare"].mean(), 2))

# 6. Сколько мужчин и женщин
print("\nМужчины / Женщины:")
print(df["Sex"].value_counts())

# 7. Выживаемость по полу
print("\nВыживаемость по полу:")
print(df.groupby("Sex")["Survived"].mean())

# 8. Выживаемость по классу каюты
print("\nВыживаемость по классу каюты:")
print(df.groupby("Pclass")["Survived"].mean())

print("\n=== Выводы ===")
print("1. Женщины выживали значительно чаще мужчин (74% против 19%).")
print("2. Чем выше класс каюты, тем выше шанс выжить (1 класс — 63%, 3 класс — 24%).")
print("3. Общая выживаемость была низкой — только около 38% пассажиров спаслись.")

# Комментарии с выводами (для ментора)
# Выводы из данных Титаника:
# - Пол сильно влиял на выживаемость: женщинам давали приоритет при спасении.
# - Класс каюты (богатство) тоже сильно влиял — пассажиры 1 класса имели больше шансов.
# - Большинство пассажиров погибло (549 из 891).